#' Интегральный коэффициент структурных сдвигов К. Гатева
#'
#' Сравнивает две структуры (например, базисного и отчётного периодов) и
#' даёт обобщающую оценку силы структурных сдвигов:
#' \deqn{K_S = \sqrt{\frac{\sum (d_1 - d_0)^2}{\sum d_0^2 + \sum d_1^2}}}{K_S = sqrt( sum (d1 - d0)^2 / (sum d0^2 + sum d1^2) )}
#' Коэффициент нормирован: \eqn{0 \le K_S \le 1}. Ноль означает одинаковые
#' структуры, единица — полностью противоположные. В отличие от
#' квадратического коэффициента Казинца он учитывает не только разности
#' долей, но и их величину: сдвиг с 20 % до 10 % даёт больший вклад, чем
#' сдвиг с 90 % до 80 % (Гатева, Гатев, § 9.3.3, формулы 9.12–9.13).
#'
#' При сравнении двух структур на один момент (например, двух регионов)
#' та же формула даёт интегральный коэффициент структурных различий
#' \eqn{K_D} (§ 9.4, формула 9.14).
#'
#' Значение коэффициента зависит от числа элементов структуры, поэтому
#' сравнивать можно только коэффициенты для структур с одинаковым числом
#' элементов.
#'
#' @param base Базисная структура: абсолютные значения, доли или проценты.
#'   Именованный числовой вектор или таблица (`data.frame`) с колонками
#'   `element` / `base` / `actual` (или `элемент` / `базис` / `отчёт`,
#'   `d0` / `d1`). Значения автоматически пересчитываются в доли.
#' @param actual Отчётная (сравниваемая) структура в том же формате.
#'   Если `base` — таблица с обеими структурами, `actual` не передаётся.
#' @return Число от 0 до 1.
#' @references Гатева Н., Гатев К. Бизнес статистика. Статистически методи
#'   в емпиричните изследвания в бизнеса. — Гл. 9, § 9.3.3.
#' @seealso [ryabtsev_index()], [struct_shift()] — все показатели сразу.
#' @export
#' @examples
#' # Пример из учебника Гатевых (табл. 9.1): экспорт фирмы «Н»
#' gatev_index(base   = c(OECD = 0.30, CEE = 0.40, Arab = 0.20, Other = 0.10),
#'             actual = c(OECD = 0.60, CEE = 0.20, Arab = 0.15, Other = 0.05))
#' # 0.43
gatev_index <- function(base, actual = NULL) {
  s <- .parse_structures(base, actual)
  .gatev(s$d0, s$d1)
}

#' Индекс структурных различий В. М. Рябцева
#'
#' \deqn{I_R = \sqrt{\frac{\sum (d_1 - d_0)^2}{\sum (d_1 + d_0)^2}}}{I_R = sqrt( sum (d1 - d0)^2 / sum (d1 + d0)^2 )}
#' Индекс нормирован (\eqn{0 \le I_R \le 1}) и, в отличие от других
#' обобщающих показателей, имеет шкалу оценки — см. [ryabtsev_scale()].
#' Подходит как для структурных сдвигов во времени, так и для различий
#' между структурами в пространстве.
#'
#' @inheritParams gatev_index
#' @param interpret Если `TRUE`, к числу добавляется атрибут
#'   `"interpretation"` с оценкой по шкале Рябцева.
#' @return Число от 0 до 1.
#' @references Афанасьев В. Н. Статистические методы в исследовании
#'   изменений структуры и элементов затрат на производство электроэнергии
#'   // Вестник НГУЭУ. — 2019. — № 4. — С. 286–303 (формула 9).
#'
#'   Перстенёва Н. П. Критерии классификации показателей структурных
#'   различий и сдвигов // Фундаментальные исследования. — 2012. — № 3
#'   (формула 12).
#' @seealso [ryabtsev_scale()], [struct_shift()].
#' @export
#' @examples
#' ryabtsev_index(base   = c(0.30, 0.40, 0.20, 0.10),
#'                actual = c(0.60, 0.20, 0.15, 0.05))
#' ryabtsev_scale(0.32)
ryabtsev_index <- function(base, actual = NULL, interpret = FALSE) {
  s <- .parse_structures(base, actual)
  out <- .ryabtsev(s$d0, s$d1)
  if (interpret) attr(out, "interpretation") <- ryabtsev_scale(out)
  out
}

#' Шкала оценки индекса Рябцева
#'
#' Без аргументов возвращает шкалу целиком, с аргументом — словесную
#' оценку для каждого значения индекса.
#'
#' | Значение индекса | Оценка |
#' |---|---|
#' | 0,000 – 0,030 | тождественность структур |
#' | 0,031 – 0,070 | весьма низкий уровень различия структур |
#' | 0,071 – 0,150 | низкий уровень различия структур |
#' | 0,151 – 0,300 | существенный уровень различия структур |
#' | 0,301 – 0,500 | значительный уровень различия структур |
#' | 0,501 – 0,700 | весьма значительный уровень различия структур |
#' | 0,701 – 0,900 | противоположный тип структур |
#' | 0,901 и выше | полная противоположность структур |
#'
#' Шкала относится только к индексу Рябцева. Для других показателей
#' (в том числе коэффициента Гатева) шкал в литературе нет
#' (Перстенёва, 2012), и применять к ним эту шкалу некорректно.
#'
#' @param x Значения индекса Рябцева или `NULL`.
#' @return Таблица шкалы (`data.frame`) или символьный вектор оценок.
#' @references Зарова Е. В., Чудилин Г. А. Региональная статистика:
#'   учебник. — М.: Финансы и статистика, 2006.
#' @export
#' @examples
#' ryabtsev_scale()
#' ryabtsev_scale(c(0.02, 0.2, 0.95))
ryabtsev_scale <- function(x = NULL) {
  tbl <- .ryabtsev_scale_tbl
  if (is.null(x)) return(tbl)
  if (!is.numeric(x) || any(x < 0 | x > 1, na.rm = TRUE)) {
    stop("Индекс Рябцева принимает значения от 0 до 1.", call. = FALSE)
  }
  # Верхние границы интервалов включаются: всё, что больше 0,030, уже
  # «весьма низкий уровень», даже если в шкале он начинается с 0,031.
  idx <- findInterval(x, tbl$to, left.open = TRUE) + 1L
  idx <- pmin(idx, nrow(tbl))
  out <- tbl$level[idx]
  out[is.na(x)] <- NA_character_
  out
}

.ryabtsev_scale_tbl <- data.frame(
  from = c(0, 0.031, 0.071, 0.151, 0.301, 0.501, 0.701, 0.901),
  to   = c(0.030, 0.070, 0.150, 0.300, 0.500, 0.700, 0.900, 1),
  level = c(
    "тождественность структур",
    "весьма низкий уровень различия структур",
    "низкий уровень различия структур",
    "существенный уровень различия структур",
    "значительный уровень различия структур",
    "весьма значительный уровень различия структур",
    "противоположный тип структур",
    "полная противоположность структур"
  ),
  stringsAsFactors = FALSE
)

#' Коэффициенты структурных сдвигов Л. С. Казинца
#'
#' Четыре классических (ненормированных) коэффициента; \eqn{k} — число
#' элементов структуры, \eqn{d_0, d_1} — доли в базисном и отчётном периоде.
#'
#' * `linear_abs` — линейный коэффициент абсолютных сдвигов
#'   \eqn{\sum |d_1 - d_0| / k}: на сколько пунктов в среднем изменились доли.
#' * `quadratic_abs` — квадратический коэффициент абсолютных сдвигов
#'   \eqn{\sqrt{\sum (d_1 - d_0)^2 / k}}.
#' * `linear_rel` — линейный коэффициент относительных сдвигов
#'   \eqn{\sum |d_1 / d_0 - 1| \cdot d_0}: средняя интенсивность изменения долей
#'   (взвешенная по базисным долям).
#' * `quadratic_rel` — квадратический коэффициент относительных сдвигов
#'   \eqn{\sqrt{\sum (d_1 / d_0 - 1)^2 d_0}}: среднее отклонение темпов роста
#'   долей от единицы. Не определён, если какая-то базисная доля равна нулю,
#'   а отчётная — нет (тогда `NA` с предупреждением).
#'
#' Коэффициенты возвращаются в долях единицы; для процентных пунктов
#' умножьте на 100.
#'
#' @inheritParams gatev_index
#' @return Именованный числовой вектор из четырёх коэффициентов.
#' @references Гатева Н., Гатев К. Бизнес статистика. — § 9.3.2, формулы 9.6–9.9.
#'
#'   Казинец Л. С. Темпы роста и структурные сдвиги в экономике. —
#'   М.: Экономика, 1981.
#' @export
#' @examples
#' kazinets(base = c(0.30, 0.40, 0.20, 0.10), actual = c(0.60, 0.20, 0.15, 0.05))
kazinets <- function(base, actual = NULL) {
  s <- .parse_structures(base, actual)
  .kazinets(s$d0, s$d1)
}

#' Индекс Салаи
#'
#' \deqn{I_{Sz} = \sqrt{\frac{1}{k}\sum \left(\frac{d_1 - d_0}{d_1 + d_0}\right)^2}}{I_Sz = sqrt( sum ((d1 - d0) / (d1 + d0))^2 / k )}
#' Нормирован от 0 до 1, но очень чувствителен к малым долям: если доля
#' элемента в одном периоде равна нулю, слагаемое сразу равно 1. Если
#' элемент отсутствует в обеих структурах, индекс не определён.
#'
#' @inheritParams gatev_index
#' @return Число от 0 до 1.
#' @references Афанасьев В. Н. // Вестник НГУЭУ. — 2019. — № 4 (формула 8).
#' @export
#' @examples
#' szalai_index(base = c(0.30, 0.40, 0.20, 0.10), actual = c(0.60, 0.20, 0.15, 0.05))
szalai_index <- function(base, actual = NULL) {
  s <- .parse_structures(base, actual)
  .szalai(s$d0, s$d1, s$labels)
}

.gatev <- function(d0, d1) sqrt(sum((d1 - d0)^2) / (sum(d0^2) + sum(d1^2)))

.ryabtsev <- function(d0, d1) sqrt(sum((d1 - d0)^2) / sum((d1 + d0)^2))

.szalai <- function(d0, d1, labels) {
  both_zero <- d0 == 0 & d1 == 0
  if (any(both_zero)) {
    stop("Индекс Салаи не определён: элементы с нулевой долей в обоих периодах (",
         paste(labels[both_zero], collapse = ", "), "). Исключите их из структуры.",
         call. = FALSE)
  }
  sqrt(mean(((d1 - d0) / (d1 + d0))^2))
}

.kazinets <- function(d0, d1) {
  k <- length(d0)
  undefined <- d0 == 0 & d1 > 0
  q_rel <- if (any(undefined)) {
    warning("Квадратический коэффициент относительных сдвигов не определён: ",
            "есть элементы с нулевой базисной долей.", call. = FALSE)
    NA_real_
  } else {
    pos <- d0 > 0
    sqrt(sum((d1[pos] / d0[pos] - 1)^2 * d0[pos]))
  }
  c(
    linear_abs = sum(abs(d1 - d0)) / k,
    quadratic_abs = sqrt(sum((d1 - d0)^2) / k),
    linear_rel = sum(abs(d1 - d0)),
    quadratic_rel = q_rel
  )
}
