#' structshift: показатели структурных сдвигов и различий
#'
#' Пакет для расчёта обобщающих показателей структурных сдвигов
#' (изменения структуры во времени) и структурных различий (сравнение
#' структур в пространстве).
#'
#' Основные функции:
#' * [struct_shift()] — все показатели и расчётная таблица сразу;
#' * [gatev_index()] — интегральный коэффициент К. Гатева;
#' * [ryabtsev_index()] и [ryabtsev_scale()] — индекс В. М. Рябцева и его шкала;
#' * [kazinets()] — коэффициенты Л. С. Казинца;
#' * [szalai_index()] — индекс А. Салаи;
#' * [shift_matrix()] — попарные сравнения нескольких структур.
#'
#' Данные можно передавать в абсолютных величинах, долях или процентах:
#' функции сами пересчитывают их в доли.
